"""
That the app can be installed and will actually render.

`www/tally_connector.html` and `public/frontend/` are generated by the Vite build
and gitignored, so a fresh clone has the route rule and the controller with no
template beside them - which is a 404 on the dashboard, exactly what this site
served before the fix. Ignoring build output is right and is what CRM and
Helpdesk do; what makes it safe is a `package.json` at the **app root**, because
`bench get-app` runs `yarn install --check-files` there and that is what
`postinstall` hooks into.

This holds the manifest rather than the output, so it passes on a clean checkout
where nothing has been built yet.
"""

import json
import os

import frappe
from frappe.tests import IntegrationTestCase


def _app_root():
	# tally_connector/tally_connector/tests -> the repository root
	return os.path.abspath(os.path.join(frappe.get_app_path("tally_connector"), ".."))


class TestInstallable(IntegrationTestCase):
	def test_the_app_root_carries_a_package_json(self):
		path = os.path.join(_app_root(), "package.json")
		self.assertTrue(os.path.exists(path), "Without this, `bench get-app` never builds the frontend.")
		pkg = json.load(open(path))
		self.assertIn("postinstall", pkg.get("scripts", {}))
		self.assertIn("build", pkg.get("scripts", {}))

	def test_the_build_script_reaches_the_frontend(self):
		pkg = json.load(open(os.path.join(_app_root(), "package.json")))
		for script in ("build", "postinstall"):
			with self.subTest(script=script):
				self.assertIn("frontend", pkg["scripts"][script])

	def test_the_route_rule_points_at_a_page_that_has_a_controller(self):
		"""A generated template with no controller beside it is served to anybody."""
		from tally_connector import hooks

		targets = {r["to_route"] for r in hooks.website_route_rules}
		self.assertIn("tally_connector", targets)
		self.assertTrue(
			os.path.exists(frappe.get_app_path("tally_connector", "www", "tally_connector.py")),
			"The dashboard page has no permission gate.",
		)

	def test_the_frontend_build_target_matches_the_route(self):
		"""Vite writes `www/<app>.html`; the route rule must name the same page."""
		vite = open(os.path.join(_app_root(), "frontend", "vite.config.js")).read()
		self.assertIn("getAppName()", vite)
		self.assertIn("www/${getAppName()}.html", vite)

	def test_public_ships_a_marker_so_it_exists_in_a_clone(self):
		"""`public/` must be in the repository, not only in the build output.

		`frappe/build.py` creates the /assets/<app> symlink only for an app
		whose public directory already exists when `bench build` runs:

		    if os.path.isdir(app_assets):
		        symlinks[app_assets] = os.path.join(assets_path, app_name)

		Everything this app puts under public/ is Vite output and gitignored, so
		without a committed file the directory is absent from a clone. A
		deployment that runs `bench build` before the frontend build then makes
		no symlink at all, every /assets/tally_connector/... URL 404s, and the
		dashboard is a blank page - with nothing wrong on the server and nothing
		in any log. That is exactly what a Frappe Cloud install did.

		The assertion names the marker file rather than asking whether public/
		holds anything, because `bench build` puts a `node_modules` symlink in
		there itself - so "public/ is not empty" is true on any machine that has
		run a build, which is every machine this test runs on. The first version
		of this test did exactly that and passed with the marker deleted.
		"""
		marker = frappe.get_app_path("tally_connector", "public", ".gitkeep")
		self.assertTrue(
			os.path.exists(marker),
			"tally_connector/public/.gitkeep is missing. Without a committed file "
			"under public/, the directory does not exist in a fresh clone, "
			"`bench build` creates no /assets symlink, and the dashboard serves a "
			"blank page with every asset 404ing.",
		)

	def test_patches_txt_carries_both_sections(self):
		"""A patches.txt missing a section aborts the whole migrate, for every app.

		Frappe reads it once per patch type and throws
		`Patch type PatchType.pre_model_sync not found in patches.txt` if the
		header is absent - which is not a tally_connector failure, it is
		`bench migrate` refusing to run at all on the site. Found by doing
		exactly that.
		"""
		path = frappe.get_app_path("tally_connector", "patches.txt")
		self.assertTrue(os.path.exists(path))
		body = open(path).read()
		for section in ("[pre_model_sync]", "[post_model_sync]"):
			with self.subTest(section=section):
				self.assertIn(section, body)

	def test_every_patch_listed_can_be_imported(self):
		"""A patch named in patches.txt that does not import fails the migrate."""
		import importlib

		path = frappe.get_app_path("tally_connector", "patches.txt")
		for line in open(path):
			line = line.strip()
			if not line or line.startswith("#") or line.startswith("["):
				continue
			with self.subTest(patch=line):
				module = importlib.import_module(line.split()[0])
				self.assertTrue(hasattr(module, "execute"), f"{line} has no execute().")

	def test_the_lockfile_parses(self):
		"""The committed lockfile was corrupt, so `yarn install` failed outright
		and the frontend could not be built from a clone at all."""
		path = os.path.join(_app_root(), "frontend", "yarn.lock")
		self.assertTrue(os.path.exists(path))
		head = open(path).readline()
		self.assertTrue(head.startswith("#"), "yarn.lock does not start with its header comment.")
