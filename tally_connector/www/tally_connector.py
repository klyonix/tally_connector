"""
tally_connector/www/tally_connector.py

The permission gate in front of the dashboard SPA.

`www/tally_connector.html` is generated by the Vite build, and a Frappe page with
no controller beside it is served to anybody who asks - including a signed-out
visitor. The endpoints behind it are fenced, so the worst case was an empty
dashboard rather than a leak, but a page that renders its controls and then
refuses every one of them is a worse answer than a redirect to the login.
"""

import frappe
from frappe import _

from tally_connector.api.export import EXPORT_ROLES

no_cache = 1


def get_context(context):
    if frappe.session.user == "Guest":
        frappe.local.flags.redirect_location = "/login?redirect-to=/tally-connector"
        raise frappe.Redirect

    if frappe.session.user != "Administrator" and not set(EXPORT_ROLES) & set(frappe.get_roles()):
        frappe.throw(
            _("You do not have access to Tally Connector. This needs one of: {0}.").format(
                ", ".join(EXPORT_ROLES)
            ),
            frappe.PermissionError,
        )

    context.no_cache = 1
    return context
